// Generates the CSS entry points from the built theme objects (single source of truth).
import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  flowbiteTokens,
  ROOT_CSS,
  slateProTokens,
  softTokens,
  tailwindThemeCss,
  themeToCss,
} from '../dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const header = '/* Generated by @awesome-ui/tokens. Do not edit. */\n';

mkdirSync(dist, { recursive: true });

// Tailwind v4 entry: registers token namespaces (bg-primary-600, rounded-control, …).
writeFileSync(join(dist, 'theme.css'), `${header}${tailwindThemeCss(flowbiteTokens)}\n`);

// Plain CSS: the three built-in themes scoped by [data-aui-theme], plus wrapper base styles.
const themes = [flowbiteTokens, slateProTokens, softTokens].map((t) => themeToCss(t)).join('\n\n');
writeFileSync(join(dist, 'themes.css'), `${header}${ROOT_CSS}\n\n${themes}\n`);

cpSync(join(root, 'src', 'fonts'), join(dist, 'fonts'), { recursive: true });
console.log('tokens: wrote dist/theme.css, dist/themes.css, dist/fonts/*');
